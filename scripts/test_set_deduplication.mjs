import handler from '../api/set.js';

class MockRes {
  statusCode = 200;
  headers = {};
  body = null;
  setHeader(k, v) { this.headers[k] = v; }
  end(data) { this.body = data; }
}

const testCases = [
  { name: 'Artist: The Weeknd', body: { artist: 'the-weeknd', lang: 'english' } },
  { name: 'Artist: Bruno Mars', body: { artist: 'bruno-mars', lang: 'english' } },
  { name: 'Artist: Drake', body: { artist: 'drake', lang: 'english' } },
  { name: 'Artist: Arijit Singh', body: { artist: 'arijit-singh', lang: 'hindi' } },
  { name: 'Artist: Taylor Swift', body: { artist: 'taylor-swift', lang: 'english' } },
  { name: 'Category: Hindi Romantic', body: { answers: { languages: ['hindi'], subtypes: ['romantic'] } } },
  { name: 'Category: English Pop', body: { answers: { languages: ['english'], subtypes: ['pop'] } } },
  { name: 'Category: English Hiphop', body: { answers: { languages: ['english'], subtypes: ['hiphop'] } } },
  { name: 'Category: Punjabi Party', body: { answers: { languages: ['punjabi'], subtypes: ['party'] } } },
  { name: 'Category: Multi-language All', body: { answers: { languages: ['hindi', 'english', 'punjabi'] } } },
];

let allPassed = true;
for (const tc of testCases) {
  const req = { method: 'POST', url: '/api/set', body: JSON.stringify(tc.body) };
  const res = new MockRes();
  await handler(req, res);
  const data = JSON.parse(res.body);
  const cues = data.cues || [];
  const vids = cues.map(c => c.youtube_ids[0]);
  const uniqueVids = new Set(vids);
  const titles = cues.map(c => c.title.toLowerCase().trim());
  const uniqueTitles = new Set(titles);

  const hasDupeVids = vids.length !== uniqueVids.size;
  const hasDupeTitles = titles.length !== uniqueTitles.size;

  const status = (!hasDupeVids && !hasDupeTitles) ? 'PASS' : 'FAIL';
  console.log(`[${status}] ${tc.name}: ${cues.length} cues, unique vids: ${uniqueVids.size}/${vids.length}, unique titles: ${uniqueTitles.size}/${titles.length}`);

  if (hasDupeVids || hasDupeTitles) {
    allPassed = false;
    console.error(`  FAILURE in ${tc.name}: dupeVids=${hasDupeVids}, dupeTitles=${hasDupeTitles}`);
  }
}

if (allPassed) {
  console.log('\nSUCCESS: 100% of sets generated by api/set.js have ZERO duplicate video IDs and ZERO duplicate titles!');
} else {
  console.error('\nFAILURE: Duplicates detected!');
  process.exit(1);
}
